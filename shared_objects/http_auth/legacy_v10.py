"""Verifies requests still signed by an old bittensor v10 Dendrite.

During the migration transition window a validator running the new FastAPI server may
still receive requests from a miner/validator that hasn't upgraded off bittensor v10's
Axon/Dendrite/Synapse stack. v10 signed every request with its own scheme (not btauth/1):

    message = f"{nonce}.{sender_hotkey}.{receiver_hotkey}.{uuid}.{body_hash}"

sent as the `bt_header_dendrite_*`/`bt_header_axon_*` headers, verified with an sr25519
signature under the substrate signing context, plus a monotonic-nonce replay check keyed
by `{sender_hotkey}:{uuid}`. `body_hash` is SHA3-256 over the concatenation of SHA3-256
hashes of `str(field_value)` for each of the message type's declared hash fields (NOT a
hash of the raw body bytes), so it must be recomputed per message type using
vanta_protocol's LEGACY_HASH_FIELDS.

This is intentionally a bridge, not a long-term scheme: it doesn't bind the HTTP method
or path (unlike btauth/1). See SIGNED-REQUESTS.md's "Accepting legacy (v10 SDK)
callers" section, and MIGRATION-GUIDE.md's "Axon, Dendrite, and Synapse are gone" section.

Verified byte-for-byte against bittensor 10.3.0's actual source
(bittensor/core/axon.py:default_verify, bittensor/core/synapse.py:body_hash,
bittensor/utils/get_hash) and against real fixtures generated by a live
bittensor.Dendrite.preprocess_synapse_for_request call — see tests/fixtures/http_auth/.
"""
import hashlib
import json
import threading
import time
from dataclasses import dataclass
from typing import Mapping, Optional

import bittensor as bt

from shared_objects.http_auth.exceptions import BadSignature, MalformedAuth, ReplayedRequest, StaleRequest

# v10's nonce freshness check only applied to dendrite_version >= 7.2.0 ("V_7_2_0" in
# bittensor.utils.axon_utils); older peers got no freshness window, only the monotonic
# check. We don't expect sub-7.2.0 peers on this subnet, but replicate the real behavior.
_V_7_2_0 = 7_002_000
_ALLOWED_NONCE_WINDOW_NS = 4_000_000_000  # 4 seconds, from bittensor.utils.axon_utils


def _get_hash(content: str) -> str:
    return hashlib.sha3_256(content.encode("utf-8")).hexdigest()


def legacy_body_hash(body: dict, hash_fields: tuple) -> str:
    hashes = [_get_hash(str(body.get(field))) for field in hash_fields]
    return _get_hash("".join(hashes))


class LegacyNonceStore:
    """Replicates bittensor.core.axon.Axon's per-endpoint-key nonce tracking.

    Keyed by f"{sender_hotkey}:{uuid}" (not just hotkey — a v10 Dendrite mints a new
    uuid per instance, so this matches v10's own endpoint_key convention exactly).
    """

    def __init__(self):
        self._nonces: dict[str, int] = {}
        self._lock = threading.Lock()

    def check_and_store(self, endpoint_key: str, nonce: int, timeout_s: float) -> bool:
        now_ns = time.time_ns()
        with self._lock:
            prev = self._nonces.get(endpoint_key)
            if prev is None:
                if now_ns - nonce > _ALLOWED_NONCE_WINDOW_NS + timeout_s * 1e9:
                    return False
            elif nonce <= prev:
                return False
            self._nonces[endpoint_key] = nonce
            return True


_default_legacy_nonce_store = LegacyNonceStore()


@dataclass
class LegacyCaller:
    hotkey_ss58: str
    nonce_ns: int


def verify_v10(
    headers: Mapping[str, str],
    body: bytes,
    *,
    self_hotkey_ss58: str,
    hash_fields: tuple,
    timeout_s: float = 12.0,
    nonce_store: Optional[LegacyNonceStore] = None,
) -> LegacyCaller:
    """Verify a legacy bittensor v10 signed request. Raises an AuthError subclass on failure."""
    lowered = {k.lower(): v for k, v in headers.items()}

    sender = lowered.get("bt_header_dendrite_hotkey")
    nonce_raw = lowered.get("bt_header_dendrite_nonce")
    req_uuid = lowered.get("bt_header_dendrite_uuid")
    signature_raw = lowered.get("bt_header_dendrite_signature")
    computed_body_hash = lowered.get("computed_body_hash")

    if not sender or not nonce_raw or not req_uuid or not signature_raw or not computed_body_hash:
        raise MalformedAuth("missing one or more legacy bt_header_dendrite_* fields")

    try:
        nonce = int(nonce_raw)
    except ValueError:
        raise MalformedAuth("bt_header_dendrite_nonce is not an integer") from None

    try:
        parsed_body = json.loads(body)
    except ValueError:
        raise MalformedAuth("body is not valid JSON") from None

    recomputed_hash = legacy_body_hash(parsed_body, hash_fields)
    if recomputed_hash != computed_body_hash:
        raise BadSignature("legacy computed_body_hash does not match the recomputed body hash")

    # v10 rebuilds the message using the RECEIVING axon's own hotkey, never a header value.
    message = f"{nonce}.{sender}.{self_hotkey_ss58}.{req_uuid}.{computed_body_hash}"

    try:
        signature = bytes.fromhex(signature_raw.removeprefix("0x"))
        keypair = bt.sp_core.Keypair(ss58_address=sender)
        valid = keypair.verify(message.encode(), signature)
    except Exception:
        raise MalformedAuth("invalid legacy hotkey address or signature encoding") from None

    if not valid:
        raise BadSignature("legacy signature does not verify against the claimed hotkey")

    store = nonce_store if nonce_store is not None else _default_legacy_nonce_store
    endpoint_key = f"{sender}:{req_uuid}"
    if not store.check_and_store(endpoint_key, nonce, timeout_s):
        raise ReplayedRequest("legacy nonce was stale or already seen for this endpoint")

    return LegacyCaller(hotkey_ss58=sender, nonce_ns=nonce)
